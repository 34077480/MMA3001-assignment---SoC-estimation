"""EKF checks: analytic Jacobians vs central finite differences, filter consistency, Coulomb counting.

Uses the fitted 2-RC parameters (results/ecm_theta_2rc.npy) with both the synthetic and, if the dataset
is present, the real OCV table.
"""
import numpy as np
import pytest

from socest.data import DT, Q_REF
from socest.ecm import TREF_X, _ocv, _param, simulate
from socest.ekf import coulomb_count, ekf

TAB = None   # set per test from the OCV fixture


def h(theta, x, i, T):
    xk = 1000.0 / (T + 273.15) - TREF_X
    return _ocv(*TAB, x[0], T)[0] + _param(theta[0], x[0], xk)[0] * i + x[1:].sum()


def f(theta, x, i, T):
    xk = 1000.0 / (T + 273.15) - TREF_X
    out = x.copy()
    out[0] = x[0] + i * DT / (3600 * Q_REF)
    for m in range(len(x) - 1):
        R = _param(theta[1 + 2 * m], x[0], xk)[0]
        tau = _param(theta[2 + 2 * m], x[0], xk)[0]
        a = np.exp(-DT / tau)
        out[1 + m] = a * x[1 + m] + R * (1 - a) * i
    return out


def analytic(theta, x, i, T):
    """Same expressions as in ekf.ekf, written out in numpy."""
    xk = 1000.0 / (T + 273.15) - TREF_X
    n = len(x)
    _, docv = _ocv(*TAB, x[0], T)
    _, dr0 = _param(theta[0], x[0], xk)
    H = np.ones(n)
    H[0] = docv + dr0 * i
    F = np.eye(n)
    for m in range(n - 1):
        R, dR = _param(theta[1 + 2 * m], x[0], xk)
        tau, dtau = _param(theta[2 + 2 * m], x[0], xk)
        a = np.exp(-DT / tau)
        da = a * DT / tau ** 2 * dtau
        F[1 + m, 1 + m] = a
        F[1 + m, 0] = da * x[1 + m] + (dR * (1 - a) - R * da) * i
    return H, F


def numeric(theta, x, i, T, eps=1e-6):
    n = len(x)
    H, F = np.zeros(n), np.zeros((n, n))
    for j in range(n):
        d = np.zeros(n)
        d[j] = eps
        H[j] = (h(theta, x + d, i, T) - h(theta, x - d, i, T)) / (2 * eps)
        F[:, j] = (f(theta, x + d, i, T) - f(theta, x - d, i, T)) / (2 * eps)
    return H, F


@pytest.mark.parametrize("which", ["synthetic_ocv", "real_ocv"])
def test_jacobians(which, theta2, request):
    global TAB
    oc = request.getfixturevalue(which)
    TAB = (oc.table, oc.s0, oc.ds)
    theta = theta2
    rng = np.random.default_rng(1)
    worst = 0.0
    for _ in range(300):
        # stay away from OCV grid nodes (0.001 apart), where the piecewise-linear derivative jumps
        s = np.floor(rng.uniform(0.05, 0.95) * 1000) / 1000 + 0.0005
        s = s if min(abs(s - k) for k in (0.1, 0.2, 0.4, 0.6, 0.8)) > 1e-4 else s + 0.0002
        x = np.array([s, rng.uniform(-0.1, 0), rng.uniform(-0.1, 0)])
        i, T = rng.uniform(-15, 8), rng.uniform(-20, 30)
        Ha, Fa = analytic(theta, x, i, T)
        Hn, Fn = numeric(theta, x, i, T)
        scale = np.maximum(np.abs(np.r_[Hn, Fn.ravel()]), 1e-3)
        err = np.max(np.abs(np.r_[Ha - Hn, (Fa - Fn).ravel()]) / scale)
        worst = max(worst, err)
    print(f"  worst relative Jacobian error over 300 random states: {worst:.2e}")
    assert worst < 1e-3


def test_noise_free_tracking(synthetic_ocv, theta2):
    """Synthetic data generated by the model itself: the EKF must converge from a wrong start and its
    3-sigma band must contain the truth almost everywhere after convergence."""
    global TAB
    TAB = (synthetic_ocv.table, synthetic_ocv.s0, synthetic_ocv.ds)
    theta = theta2
    n = 60000
    rng = np.random.default_rng(0)
    i = np.repeat(rng.uniform(-8, 4, n // 50), 50)
    T = np.full(n, 25.0)
    s_true = coulomb_count(i, DT, 0.9)
    v = simulate(theta, s_true, T, i, DT, *TAB) + 0.002 * rng.standard_normal(n)
    soc, sig, _ = ekf(theta, v, i, T, DT, *TAB, 0.6, 0.1, 1e-10, 1e-7, 0.002 ** 2)
    late = slice(n // 3, None)
    err = np.abs(soc - s_true)[late]
    cover = np.mean(err <= 3 * sig[late])
    print(f"  synthetic: final err {abs(soc[-1]-s_true[-1])*100:.3f}% SoC, 3-sigma coverage {cover*100:.1f}%")
    assert err.max() < 0.01 and cover > 0.95



def test_coulomb_count_constant_current():
    """Constant 1C discharge for 30 min must remove exactly half the charge (rectangle rule is exact)."""
    n = int(1800 / DT)
    s = coulomb_count(np.full(n + 1, -Q_REF), DT, 1.0)
    assert abs(s[-1] - 0.5) < 1e-12


def test_coulomb_count_bias_drift():
    """A current bias b drifts the estimate linearly by b t / (3600 Q): the baseline's known failure mode."""
    n = int(3600 / DT)
    s = coulomb_count(np.full(n + 1, 0.05), DT, 0.5)
    assert abs((s[-1] - 0.5) - 0.05 / Q_REF) < 1e-10   # 36 000 additions: allow rounding


def test_numba_matches_numpy_reference(synthetic_ocv, theta2):
    """The optimised (numba, explicit loops) EKF must equal the readable NumPy implementation."""
    from socest.ekf import ekf_reference
    oc = synthetic_ocv
    n = 3000
    rng = np.random.default_rng(2)
    i = np.repeat(rng.uniform(-10, 5, n // 30), 30)
    T = np.linspace(-15, 25, n)
    v = simulate(theta2, coulomb_count(i, DT, 0.8), T, i, DT, oc.table, oc.s0, oc.ds) + 0.003 * rng.standard_normal(n)
    args = (theta2, v, i, T, DT, oc.table, oc.s0, oc.ds, 0.6, 0.04, 1e-8, 1e-7, 0.01)
    a, b = ekf(*args), ekf_reference(*args)
    for x, y in zip(a, b):
        assert np.max(np.abs(x - y)) < 1e-10
